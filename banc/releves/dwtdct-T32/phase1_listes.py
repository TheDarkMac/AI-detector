"""Phase 1 du relevé de T32 : listes de fichiers de Wikimedia Commons.

Deux listes, écrites dans ``phase1.jsonl`` (un enregistrement JSON par ligne, champ ``liste``) :

- ``authentique`` : JPEG et PNG versés avant le 2022-08-22, date de la publication de Stable
  Diffusion 1 ; aucun ne peut porter un des trois messages cherchés. Pour chaque mois de 2008-01
  à 2022-07, quatre appels de 25 fichiers (``generator=allimages``), à partir des jours 1, 8, 15
  et 22 à midi, pour ne pas tomber sur un seul lot versé d'un coup ; la largeur du rendu de
  960 pixels est demandée (``iiurlwidth``).
- ``declare`` : fichiers que Commons range parmi les images générées par Stable Diffusion, ou qui
  nomment SDXL ou FLUX.1 dans leur description (recherche CirrusSearch, :data:`RECHERCHES`). Leur
  origine n'est pas vérifiée : c'est ce que leur page déclare.

Reprend là où il s'est arrêté (``phase1.etat.json``). Une requête à la fois, ``maxlag=5``.
"""

from __future__ import annotations

import http.client
import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any

type Fiche = dict[str, Any]
"""Un enregistrement JSON du relevé."""

ICI = Path(__file__).resolve().parent
SORTIE = ICI / "phase1.jsonl"
ETAT = ICI / "phase1.etat.json"
API = "https://commons.wikimedia.org/w/api.php"
AGENT = "voight-kampff-releve/0.1 (https://github.com/TheDarkMac/AI-detector)"
JOURS = (1, 8, 15, 22)
PAR_APPEL = 25
LARGEUR_RENDU = 960
TYPES = frozenset({"image/jpeg", "image/png"})
RECHERCHES = (
    'deepcat:"Images generated by Stable Diffusion"',
    '"SDXL" filetype:bitmap',
    '"FLUX.1" filetype:bitmap',
)
PROPRIETES = "url|user|mime|size|timestamp|extmetadata"
FILTRE = "LicenseShortName|Artist"


def appeler(parametres: dict[str, str]) -> Fiche:
    adresse = API + "?" + urllib.parse.urlencode(parametres)
    essai = 0
    while True:
        essai += 1
        # Adresse fixe en https de l'API de Commons : aucun autre schéma possible.
        requete = urllib.request.Request(adresse, headers={"User-Agent": AGENT})  # noqa: S310
        try:
            with urllib.request.urlopen(requete, timeout=60) as reponse:  # noqa: S310
                donnees: Fiche = json.load(reponse)
        except (OSError, http.client.HTTPException, json.JSONDecodeError) as erreur:
            attente = min(300, 10 * essai)
            if isinstance(erreur, urllib.error.HTTPError) and erreur.headers.get("Retry-After"):
                attente = max(attente, int(erreur.headers["Retry-After"]))
            print(f"erreur {erreur!r}, attente {attente} s", file=sys.stderr, flush=True)
            time.sleep(attente)
            continue
        if "error" in donnees:
            if donnees["error"].get("code") == "maxlag":
                time.sleep(10)
                continue
            raise RuntimeError(donnees["error"])
        time.sleep(1)
        return donnees


def fiche(page: Fiche, liste: str) -> Fiche | None:
    """Enregistrement d'une page de fichier rendue par ``prop=imageinfo`` ; ``None`` hors
    JPEG et PNG."""
    infos = (page.get("imageinfo") or [{}])[0]
    if infos.get("mime") not in TYPES:
        return None
    meta = infos.get("extmetadata") or {}
    return {
        "liste": liste,
        "nom": page["title"].removeprefix("File:"),
        "page": infos.get("descriptionurl"),
        "adresse": infos.get("url"),
        "rendu": infos.get("thumburl"),
        "type": infos["mime"],
        "compte": infos.get("user"),
        "versement": infos.get("timestamp"),
        "largeur": infos.get("width"),
        "hauteur": infos.get("height"),
        "taille": infos.get("size"),
        "licence": (meta.get("LicenseShortName") or {}).get("value"),
    }


def debuts() -> list[str]:
    return [
        f"{annee}-{mois:02d}-{jour:02d}T12:00:00Z"
        for annee in range(2008, 2023)
        for mois in range(1, 13)
        if (annee, mois) <= (2022, 7)
        for jour in JOURS
    ]


def authentiques(sortie: Any, faits: set[str]) -> None:
    for debut in debuts():
        if debut in faits:
            continue
        donnees = appeler(
            {
                "action": "query",
                "format": "json",
                "formatversion": "2",
                "generator": "allimages",
                "gaisort": "timestamp",
                "gaidir": "newer",
                "gaistart": debut,
                "gailimit": str(PAR_APPEL),
                "prop": "imageinfo",
                "iiprop": PROPRIETES,
                "iiextmetadatafilter": FILTRE,
                "iiurlwidth": str(LARGEUR_RENDU),
                "maxlag": "5",
            }
        )
        for page in donnees.get("query", {}).get("pages", []):
            enregistrement = fiche(page, "authentique")
            if enregistrement is not None and enregistrement["versement"] < "2022-08-22":
                sortie.write(json.dumps(enregistrement, ensure_ascii=False) + "\n")
        sortie.flush()
        faits.add(debut)
        ETAT.write_text(json.dumps(sorted(faits)))
        print(f"{debut} fait", flush=True)


def declares(sortie: Any, faits: set[str]) -> None:
    for recherche in RECHERCHES:
        if recherche in faits:
            continue
        suite: dict[str, str] = {}
        while True:
            donnees = appeler(
                {
                    "action": "query",
                    "format": "json",
                    "formatversion": "2",
                    "generator": "search",
                    "gsrsearch": recherche,
                    "gsrnamespace": "6",
                    "gsrlimit": "50",
                    "prop": "imageinfo",
                    "iiprop": PROPRIETES,
                    "iiextmetadatafilter": FILTRE,
                    "maxlag": "5",
                    **suite,
                }
            )
            for page in donnees.get("query", {}).get("pages", []):
                enregistrement = fiche(page, "declare")
                if enregistrement is not None:
                    enregistrement["recherche"] = recherche
                    sortie.write(json.dumps(enregistrement, ensure_ascii=False) + "\n")
            sortie.flush()
            suite = donnees.get("continue", {})
            suite.pop("continue", None)
            if not suite:
                break
        faits.add(recherche)
        ETAT.write_text(json.dumps(sorted(faits)))
        print(f"{recherche} fait", flush=True)


def main() -> None:
    faits = set(json.loads(ETAT.read_text())) if ETAT.exists() else set()
    with SORTIE.open("a", encoding="utf-8") as sortie:
        declares(sortie, faits)
        authentiques(sortie, faits)


if __name__ == "__main__":
    main()
